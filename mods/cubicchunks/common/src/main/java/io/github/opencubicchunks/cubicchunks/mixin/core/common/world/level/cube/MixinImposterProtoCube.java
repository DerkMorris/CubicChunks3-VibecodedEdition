package io.github.opencubicchunks.cubicchunks.mixin.core.common.world.level.cube;

import java.util.Collection;
import java.util.Map;

import io.github.opencubicchunks.cubicchunks.world.level.chunklike.ImposterProtoClo;
import io.github.opencubicchunks.cubicchunks.world.level.chunklike.LevelClo;
import io.github.opencubicchunks.cubicchunks.world.level.cube.ImposterProtoCube;
import io.github.opencubicchunks.cubicchunks.world.level.cube.LevelCube;
import io.github.opencubicchunks.cubicchunks.world.level.levelgen.heightmap.CloHeightmap;
import net.minecraft.world.level.levelgen.Heightmap;
import org.spongepowered.asm.mixin.Dynamic;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;

@Mixin(ImposterProtoCube.class)
public abstract class MixinImposterProtoCube extends MixinProtoCube implements ImposterProtoClo {
    // Field generated by DASM
    @Dynamic @Shadow @Final private LevelCube wrapped;

    @Override public LevelClo cc_getWrappedClo() {
        return this.wrapped;
    }

    @Override public Collection<Map.Entry<Heightmap.Types, CloHeightmap>> cc_getHeightmaps() {
        return this.wrapped.cc_getHeightmaps();
    }

    @Override public boolean hasPrimedHeightmap(Heightmap.Types type) {
        return this.wrapped.hasPrimedHeightmap(type);
    }

    /** Derived caches belong to the wrapped sections even when this view rejects block writes. */
    public void cc_restoreHeightmaps(Map<Heightmap.Types, long[]> snapshot) {
        this.wrapped.cc_restoreHeightmaps(snapshot);
    }

    public void cc_invalidateHeightmaps() {
        this.wrapped.cc_invalidateHeightmaps();
    }
}
